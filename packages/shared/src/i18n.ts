export const dictionaries = { en, id } satisfies Record<Locale, Record<TranslationKey, string>>;

export type TranslateVars = Record<string, string | number>;

/**
 * Looks up `key` in `locale`, falling back to English. Placeholders written as
 * `{name}` are replaced from `vars`.
 */
export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: TranslateVars,
): string {
  const template = dictionaries[locale]?.[key] ?? dictionaries.en[key] ?? key;
  if (!vars) {
    return template;
  }
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}

export function translateSection(locale: Locale, key: SectionKey): string {
  return translate(locale, `section.${key}` as TranslationKey);
}

